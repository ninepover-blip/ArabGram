CREATE FUNCTION public.channel_delivery_lanes_notify_ready()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE ready_shard smallint;
BEGIN
    FOR ready_shard IN
        SELECT DISTINCT logical_shard
        FROM new_rows
        WHERE state = 'ready' AND ready_at <= now()
    LOOP
        PERFORM pg_notify('telesrv_channel_delivery_ready', ready_shard::text);
    END LOOP;
    RETURN NULL;
END;
$$;

CREATE TRIGGER channel_delivery_lanes_insert_ready_notify
AFTER INSERT ON public.channel_delivery_lanes
REFERENCING NEW TABLE AS new_rows
FOR EACH STATEMENT EXECUTE FUNCTION public.channel_delivery_lanes_notify_ready();

CREATE TRIGGER channel_delivery_lanes_update_ready_notify
AFTER UPDATE ON public.channel_delivery_lanes
REFERENCING NEW TABLE AS new_rows
FOR EACH STATEMENT EXECUTE FUNCTION public.channel_delivery_lanes_notify_ready();

CREATE FUNCTION public.channel_delivery_attempts_notify_finalize()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE ready_shard smallint;
BEGIN
    FOR ready_shard IN
        SELECT DISTINCT l.logical_shard
        FROM new_rows a
        JOIN channel_delivery_lanes l ON l.channel_id = a.channel_id
        WHERE a.finalized_at IS NULL
          AND a.resolution <> 'pending'
    LOOP
        PERFORM pg_notify('telesrv_channel_delivery_finalize', ready_shard::text);
    END LOOP;
    RETURN NULL;
END;
$$;

CREATE TRIGGER channel_delivery_attempts_finalize_notify
AFTER UPDATE ON public.channel_delivery_attempts
REFERENCING NEW TABLE AS new_rows
FOR EACH STATEMENT EXECUTE FUNCTION public.channel_delivery_attempts_notify_finalize();

CREATE FUNCTION public.channel_delivery_attempts_notify_deadline()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ready_shard smallint;
BEGIN
    FOR ready_shard IN
        SELECT DISTINCT l.logical_shard
        FROM new_rows a
        JOIN channel_delivery_lanes l ON l.channel_id = a.channel_id
        WHERE a.finalized_at IS NULL AND a.resolution = 'pending'
    LOOP
        PERFORM pg_notify('telesrv_channel_delivery_ready', ready_shard::text);
    END LOOP;
    RETURN NULL;
END;
$$;

CREATE TRIGGER channel_delivery_attempts_deadline_notify
